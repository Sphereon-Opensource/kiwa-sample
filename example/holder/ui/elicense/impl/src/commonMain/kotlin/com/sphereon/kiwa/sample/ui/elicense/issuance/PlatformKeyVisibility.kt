import com.sphereon.crypto.core.KeyVisibility

/**
 * Returns the appropriate [KeyVisibility] for use with `toManagedKeyInfo()` calls.
 *
 * On Android with software keystore, this returns [KeyVisibility.PRIVATE] because
 * the private key material is accessible.
 *
 * On iOS with native keychain, this returns [KeyVisibility.PUBLIC] because native
 * keychain keys don't expose private key material - the KMS provider handles
 * signing operations internally.
 */
expect fun getManagedKeyInfoVisibility(): KeyVisibility
